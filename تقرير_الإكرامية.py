# تقرير صفحة واحدة: هل الطاولات الكبيرة بتدفع إكرامية أقل؟
# طريقة التشغيل من الـ Terminal:  streamlit run تقرير_الإكرامية.py

import seaborn as sns
import streamlit as st

# ---------- 1) تحميل البيانات ----------
بيانات_المطعم = sns.load_dataset("tips")

# ---------- 2) تجهيز البيانات ----------
# نسبة الإكرامية من الفاتورة لكل طاولة
بيانات_المطعم["نسبة_الإكرامية"] = بيانات_المطعم["tip"] / بيانات_المطعم["total_bill"] * 100

# نقسم الطاولات: صغيرة (شخصين) وكبيرة (3 او 4 اشخاص)
طاولات_شخصين = بيانات_المطعم[بيانات_المطعم["size"] == 2]
طاولات_كبيرة = بيانات_المطعم[بيانات_المطعم["size"].isin([3, 4])]

# ---------- 3) المؤشرات الثلاثة ----------
# المؤشر 1: وسيط نسبة الإكرامية (الوسيط لان النسبة ملتوية بسبب حالات متطرفة)
وسيط_النسبة = بيانات_المطعم["نسبة_الإكرامية"].median()

# المؤشر 2: متوسط نسبة الإكرامية للطاولات الكبيرة مقابل طاولات الشخصين
نسبة_الطاولات_الكبيرة = طاولات_كبيرة["نسبة_الإكرامية"].mean()
نسبة_طاولات_الشخصين = طاولات_شخصين["نسبة_الإكرامية"].mean()

# المؤشر 3: الدولارات المفقودة لو وصلت الطاولات الكبيرة لمستوى طاولات الشخصين
مكسب_محتمل = (نسبة_طاولات_الشخصين - نسبة_الطاولات_الكبيرة) / 100 * طاولات_كبيرة["total_bill"].sum()
نسبة_المكسب = مكسب_محتمل / بيانات_المطعم["tip"].sum() * 100

# ---------- 4) بيانات الرسمتين ----------
# الرسمة 1: متوسط النسبة حسب حجم الطاولة (1 الى 6 لكن نكتفي بالاحجام الكافية)
عدد_حسب_الحجم = بيانات_المطعم.groupby("size")["نسبة_الإكرامية"].count()
احجام_كافية = عدد_حسب_الحجم[عدد_حسب_الحجم >= 30].index
نسبة_حسب_الحجم = (
    بيانات_المطعم[بيانات_المطعم["size"].isin(احجام_كافية)]
    .groupby("size")["نسبة_الإكرامية"].mean()
)

# الرسمة 2: الفواتير الكبيرة (فوق 40 دولار) مقابل باقي الفواتير
بيانات_المطعم["فئة_الفاتورة"] = بيانات_المطعم["total_bill"].apply(
    lambda القيمة: "2 - فوق 40 دولار" if القيمة > 40 else "1 - 40 دولار او اقل"
)
نسبة_حسب_الفئة = بيانات_المطعم.groupby("فئة_الفاتورة")["نسبة_الإكرامية"].mean()

# ---------- 5) عرض الصفحة ----------
st.set_page_config(page_title="تقرير الإكرامية", layout="centered")

st.title("الطاولات الكبيرة والفواتير الضخمة بتدفع إكرامية أقل")
st.caption("السؤال: هل الإكرامية عادلة بين أحجام الطاولات المختلفة؟ (بيانات 244 طاولة)")

عمود1, عمود2, عمود3 = st.columns(3)
عمود1.metric("وسيط نسبة الإكرامية", f"{وسيط_النسبة:.1f}%")
عمود2.metric(
    "إكرامية الطاولات الكبيرة (3-4)",
    f"{نسبة_الطاولات_الكبيرة:.1f}%",
    f"{نسبة_الطاولات_الكبيرة - نسبة_طاولات_الشخصين:+.1f} عن طاولة الشخصين",
)
عمود3.metric("مكسب محتمل", f"{مكسب_محتمل:.0f} دولار", f"{نسبة_المكسب:.1f}% من الإكراميات")

st.subheader("كل ما كبرت الطاولة نزلت نسبة الإكرامية")
st.bar_chart(نسبة_حسب_الحجم)

st.subheader("الفواتير فوق 40 دولار إكراميتها أقل بشكل واضح")
st.bar_chart(نسبة_حسب_الفئة)

st.subheader("التوصية")
st.success(
    "اطبعوا على فاتورة أي مجموعة (3 اشخاص فأكثر) خيارات إكرامية مقترحة (15% و18% و20%). "
    "وبعد شهر قارنوا نسبة إكرامية المجموعات مع الارقام الحالية لنعرف اذا نفع الاقتراح."
)
